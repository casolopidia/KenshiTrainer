# ---------------- Overlay.cpp ----------------
d = io.open(OV, "rb").read()

# 1. replace the creation-hooks section (KenshiLib dxgi export hooks)
START = (b"// ---------------------------------------------------------------------------\r\n"
         b"// creation hooks (function-code hooks via KenshiLib - the DustBoot layer)\r\n"
         b"// ---------------------------------------------------------------------------\r\n")
END = b"\r\nvoid Overlay_Init()\r\n{"
i1 = d.find(START)
i2 = d.find(END, i1)
assert i1 > 0 and i2 > i1, ("creation section", i1, i2)
d = d[:i1] + NEW_SECTION_1 + NEW_SECTION_2 + NEW_SECTION_3 + d[i2:]

# 2. OnSwapChain: skip foreign temp swapchains
old = (b"static void OnSwapChain(IDXGISwapChain* sc)\r\n"
       b"{\r\n"
       b"    if (!sc)\r\n"
       b"        return;\r\n"
       b"    ShadowHookPresent(sc);\r\n")
new = (b"static bool IsForeignTempSwapChain(IDXGISwapChain* sc);\r\n"
       b"\r\n"
       b"static void OnSwapChain(IDXGISwapChain* sc)\r\n"
       b"{\r\n"
       b"    if (!sc || IsForeignTempSwapChain(sc))\r\n"
       b"        return;\r\n"
       b"    ShadowHookPresent(sc);\r\n")
assert d.count(old) == 1, "onswap"
d = d.replace(old, new)

# 3. Overlay_Init body: replace old dxgi hook installs
i1 = d.find(b'    HMODULE d3d11 = GetModuleHandleA("d3d11.dll");')
i2 = d.find(b"    g_prevUEF = SetUnhandledExceptionFilter(&TrainerUEF);", i1)
assert i1 > 0 and i2 > i1, ("init body", i1, i2)
d = d[:i1] + INIT_BODY + d[i2:]

io.open(OV, "wb").write(d)
print("Overlay.cpp patched")

