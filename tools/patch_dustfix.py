# -*- coding: utf-8 -*-
# Final Dust-coexistence fix: capture swapchain creation without KenshiLib
# hooks on the dxgi exports DustBoot also hooks (that double-hook crashed the
# game during concurrent D3D init; bisect-proven; Heisenbug under debuggers).
import io

OV = r"src\Overlay.cpp"
KT = r"src\KenshiTrainer.cpp"

NEW_SECTION_1 = (
b"// ---------------------------------------------------------------------------\r\n"
b"// swapchain creation capture WITHOUT touching the dxgi/d3d11 exports that\r\n"
b"// DustBoot hooks through KenshiLib as well. Two modules AddHook-ing the SAME\r\n"
b"// export (D3D11CreateDeviceAndSwapChain / CreateSwapChain / ...ForHwnd) crashes\r\n"
b"// the game nondeterministically during concurrent D3D init (bisect: any single\r\n"
b"// one of our dxgi-export hooks + Dust = death; uncontended exports like\r\n"
b"// D3D11CreateDevice or game functions = fine; a debugger hides it via timing).\r\n"
b"//\r\n"
b"// Capture strategy, all uncontended:\r\n"
b"//   1. KenshiLib hook on D3D11CreateDevice (export Dust never patches): when the\r\n"
b"//      game creates its device, its DXGI factory already lives on some process\r\n"
b"//      heap (OGRE creates the factory first). We walk all process heaps for\r\n"
b"//      objects whose first qword is the dxgi factory vtable, validate them\r\n"
b"//      (slots 10/15 must equal the canonical CreateSwapChain/ForHwnd), and\r\n"
b"//      redirect each object's instance vptr to one shared shadow vtable. No\r\n"
b"//      code patch anywhere, so KenshiLib has nothing to chain and no thread\r\n"
b"//      suspension is needed.\r\n"
b"//   2. KenshiLib hooks on CreateDXGIFactory1/CreateDXGIFactory catch factories\r\n"
b"//      born later (resolution changes etc.) at birth.\r\n"
b"// ---------------------------------------------------------------------------\r\n"
b"\r\n"
b"static bool IsForeignTempSwapChain(IDXGISwapChain* sc)\r\n"
b"{\r\n"
b"    // DustBoot creates a temp device + swapchain on a dummy window while it\r\n"
b"    // installs its hooks - never redirect or track those objects\r\n"
b"    DXGI_SWAP_CHAIN_DESC dd;\r\n"
b"    __try\r\n"
b"    {\r\n"
b"        if (FAILED(sc->GetDesc(&dd)) || !dd.OutputWindow)\r\n"
b"            return false;\r\n"
b"        char cls[64] = { 0 };\r\n"
b"        if (GetClassNameA(dd.OutputWindow, cls, sizeof(cls)) &&\r\n"
b"            strcmp(cls, \"DustBootDummy\") == 0)\r\n"
b"            return true;\r\n"
b"    }\r\n"
b"    __except (EXCEPTION_EXECUTE_HANDLER) {}\r\n"
b"    return false;\r\n"
b"}\r\n"
b"\r\n"
b"typedef HRESULT(STDMETHODCALLTYPE* CreateSwapChain_t)(\r\n"
b"    IDXGIFactory*, IUnknown*, DXGI_SWAP_CHAIN_DESC*, IDXGISwapChain**);\r\n"
b"static CreateSwapChain_t g_origCreateSwapChain = NULL;\r\n"
b"\r\n"
b"typedef HRESULT(STDMETHODCALLTYPE* CreateSwapChainForHwnd_t)(\r\n"
b"    IUnknown*, IUnknown*, HWND, const void*, const void*, IUnknown*, void**);\r\n"
b"static CreateSwapChainForHwnd_t g_origCSCFH = NULL;\r\n"
b"\r\n"
)
NEW_SECTION_2 = (
b"static HRESULT STDMETHODCALLTYPE CreateSwapChain_FactoryHook(\r\n"
b"    IDXGIFactory* self, IUnknown* dev, DXGI_SWAP_CHAIN_DESC* desc, IDXGISwapChain** out)\r\n"
b"{\r\n"
b"    HRESULT hr = g_origCreateSwapChain(self, dev, desc, out);\r\n"
b"    if (SUCCEEDED(hr) && out && *out && !IsForeignTempSwapChain(*out))\r\n"
b"        OnSwapChain(*out);\r\n"
b"    return hr;\r\n"
b"}\r\n"
b"\r\n"
b"static HRESULT STDMETHODCALLTYPE CreateSwapChainForHwnd_FactoryHook(\r\n"
b"    IUnknown* self, IUnknown* dev, HWND hwnd, const void* desc,\r\n"
b"    const void* fsDesc, IUnknown* output, void** out)\r\n"
b"{\r\n"
b"    HRESULT hr = g_origCSCFH(self, dev, hwnd, desc, fsDesc, output, out);\r\n"
b"    if (SUCCEEDED(hr) && out && *out && !IsForeignTempSwapChain((IDXGISwapChain*)*out))\r\n"
b"        OnSwapChain((IDXGISwapChain*)*out); // IDXGISwapChain1 derives IDXGISwapChain\r\n"
b"    return hr;\r\n"
b"}\r\n"
b"\r\n"
b"// one shared shadow vtable for every factory object (they share the live table)\r\n"
b"static void** g_factoryShadow = NULL;\r\n"
b"\r\n"
b"static void RedirectFactoryObject(void* obj)\r\n"
b"{\r\n"
b"    if (!obj || !g_factoryShadow)\r\n"
b"        return;\r\n"
b"    __try { *(void***)obj = g_factoryShadow; }\r\n"
b"    __except (EXCEPTION_EXECUTE_HANDLER) {}\r\n"
b"}\r\n"
b"\r\n"
b"// probe factory: yields the canonical vtable + slot values, builds the shadow\r\n"
b"static bool PrepareFactoryShadow()\r\n"
b"{\r\n"
b"    if (g_factoryShadow)\r\n"
b"        return true;\r\n"
b"    HMODULE dxgi = GetModuleHandleA(\"dxgi.dll\");\r\n"
b"    if (!dxgi) dxgi = LoadLibraryA(\"dxgi.dll\");\r\n"
b"    typedef HRESULT(WINAPI* CF1_t)(REFIID, void**);\r\n"
b"    CF1_t cf1 = dxgi ? (CF1_t)GetProcAddress(dxgi, \"CreateDXGIFactory1\") : NULL;\r\n"
b"    if (!cf1)\r\n"
b"        return false;\r\n"
b"    IDXGIFactory* probe = NULL;\r\n"
b"    bool ok = false;\r\n"
b"    __try\r\n"
b"    {\r\n"
b"        if (SUCCEEDED(cf1(__uuidof(IDXGIFactory), (void**)&probe)) && probe)\r\n"
b"        {\r\n"
b"            void** live = *(void***)probe;\r\n"
b"            if (live)\r\n"
b"            {\r\n"
b"                void** shadow = (void**)malloc(sizeof(void*) * 24);\r\n"
b"                if (shadow)\r\n"
b"                {\r\n"
b"                    memcpy(shadow, live, sizeof(void*) * 24);\r\n"
b"                    g_origCreateSwapChain = (CreateSwapChain_t)shadow[10];\r\n"
b"                    g_origCSCFH = (CreateSwapChainForHwnd_t)shadow[15];\r\n"
b"                    shadow[10] = (void*)&CreateSwapChain_FactoryHook;\r\n"
b"                    shadow[15] = (void*)&CreateSwapChainForHwnd_FactoryHook;\r\n"
b"                    g_factoryShadow = shadow;\r\n"
b"                    ok = true;\r\n"
b"                }\r\n"
b"            }\r\n"
b"        }\r\n"
b"    }\r\n"
b"    __except (EXCEPTION_EXECUTE_HANDLER) {}\r\n"
b"    __try { if (probe) probe->Release(); } __except (EXCEPTION_EXECUTE_HANDLER) {}\r\n"
b"    return ok;\r\n"
b"}\r\n"
b"\r\n"
)

NEW_SECTION_3 = (
b"// heap-walk discovery of every live factory object; runs a few times only\r\n"
b"static int g_factoryScanCount = 0;\r\n"
b"static void ScanHeapsForFactories()\r\n"
b"{\r\n"
b"    if (g_factoryScanCount >= 3 || !g_factoryShadow)\r\n"
b"        return;\r\n"
b"    ++g_factoryScanCount;\r\n"
b"    HANDLE heaps[64];\r\n"
b"    DWORD nHeaps = GetProcessHeaps(64, heaps);\r\n"
b"    int redirected = 0;\r\n"
b"    for (DWORD h = 0; h < nHeaps; ++h)\r\n"
b"    {\r\n"
b"        HANDLE heap = heaps[h];\r\n"
b"        if (HeapLock(heap) != TRUE)\r\n"
b"            continue;\r\n"
b"        __try\r\n"
b"        {\r\n"
b"            PROCESS_HEAP_ENTRY e;\r\n"
b"            e.lpData = NULL;\r\n"
b"            while (HeapWalk(heap, &e))\r\n"
b"            {\r\n"
b"                if (!e.lpData || e.cbData < sizeof(void*))\r\n"
b"                    continue;\r\n"
b"                void** obj = (void**)e.lpData;\r\n"
b"                void* vt = NULL;\r\n"
b"                __try { vt = obj[0]; } __except (EXCEPTION_EXECUTE_HANDLER) { continue; }\r\n"
b"                if (!vt)\r\n"
b"                    continue;\r\n"
b"                void** vtSlots = (void**)vt;\r\n"
b"                void* s10 = NULL; void* s15 = NULL;\r\n"
b"                __try { s10 = vtSlots[10]; s15 = vtSlots[15]; }\r\n"
b"                __except (EXCEPTION_EXECUTE_HANDLER) { continue; }\r\n"
b"                if (s10 != (void*)g_origCreateSwapChain ||\r\n"
b"                    s15 != (void*)g_origCSCFH)\r\n"
b"                    continue;\r\n"
b"                if (*(void***)obj != g_factoryShadow)\r\n"
b"                {\r\n"
b"                    RedirectFactoryObject(obj);\r\n"
b"                    ++redirected;\r\n"
b"                }\r\n"
b"            }\r\n"
b"        }\r\n"
b"        __except (EXCEPTION_EXECUTE_HANDLER) {}\r\n"
b"        HeapUnlock(heap);\r\n"
b"    }\r\n"
b"    { char db[96]; sprintf_s(db, \"KenshiTrainer: factory heap scan #%d redirected=%d\",\r\n"
b"        g_factoryScanCount, redirected); DebugLog(db); }\r\n"
b"}\r\n"
b"\r\n"
b"typedef HRESULT(WINAPI* D3D11CreateDevice_t)(IDXGIAdapter*, D3D_DRIVER_TYPE, HMODULE, UINT,\r\n"
b"    const D3D_FEATURE_LEVEL*, UINT, UINT, ID3D11Device**, D3D_FEATURE_LEVEL*, ID3D11DeviceContext**);\r\n"
b"static D3D11CreateDevice_t g_origD3D11CreateDevice = NULL;\r\n"
b"\r\n"
b"static HRESULT WINAPI D3D11CreateDevice_Hook(IDXGIAdapter* adapter, D3D_DRIVER_TYPE dt, HMODULE sw,\r\n"
b"    UINT flags, const D3D_FEATURE_LEVEL* levels, UINT numLevels, UINT sdk,\r\n"
b"    ID3D11Device** devOut, D3D_FEATURE_LEVEL* flOut, ID3D11DeviceContext** ctxOut)\r\n"
b"{\r\n"
b"    HRESULT hr = g_origD3D11CreateDevice(adapter, dt, sw, flags, levels, numLevels, sdk,\r\n"
b"        devOut, flOut, ctxOut);\r\n"
b"    if (SUCCEEDED(hr) && devOut && *devOut && PrepareFactoryShadow())\r\n"
b"        ScanHeapsForFactories();\r\n"
b"    return hr;\r\n"
b"}\r\n"
b"\r\n"
b"// catch factories born later (resolution changes, alt-tab paths)\r\n"
b"typedef HRESULT(WINAPI* CreateDXGIFactory1_t)(REFIID, void**);\r\n"
b"static CreateDXGIFactory1_t g_origCDGF1 = NULL;\r\n"
b"static HRESULT WINAPI CreateDXGIFactory1_Hook(REFIID riid, void** ppFactory)\r\n"
b"{\r\n"
b"    HRESULT hr = g_origCDGF1(riid, ppFactory);\r\n"
b"    if (SUCCEEDED(hr) && ppFactory && *ppFactory && PrepareFactoryShadow())\r\n"
b"        RedirectFactoryObject(*ppFactory);\r\n"
b"    return hr;\r\n"
b"}\r\n"
b"\r\n"
b"typedef HRESULT(WINAPI* CreateDXGIFactory_t)(REFIID, void**);\r\n"
b"static CreateDXGIFactory_t g_origCDGF = NULL;\r\n"
b"static HRESULT WINAPI CreateDXGIFactory_Hook(REFIID riid, void** ppFactory)\r\n"
b"{\r\n"
b"    HRESULT hr = g_origCDGF(riid, ppFactory);\r\n"
b"    if (SUCCEEDED(hr) && ppFactory && *ppFactory && PrepareFactoryShadow())\r\n"
b"        RedirectFactoryObject(*ppFactory);\r\n"
b"    return hr;\r\n"
b"}\r\n"
)

