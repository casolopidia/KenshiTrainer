# -*- coding: utf-8 -*-
# Patches KenshiTrainer.cpp (medical tab + GUI anchoring) and Overlay.cpp
# (stale ini wipe). Byte-level, CRLF-aware, every anchor must match exactly once.
import io, sys

def patch(path, edits):
    with io.open(path, "rb") as f:
        data = f.read()
    for name, old, new in edits:
        n = data.count(old)
        assert n == 1, "%s: anchor %r matched %d times" % (path, name, n)
        data = data.replace(old, new)
    with io.open(path, "wb") as f:
        f.write(data)
    print("%s: %d edits applied" % (path, len(edits)))

